@dataclass
class TableShape:
    copy_columns: list[str] = field(default_factory=list)
    check_columns: list[str] = field(default_factory=list)


def table_shape(conn: psycopg.Connection, table: str, schema: str = "public") -> TableShape:
    """Column lists in attnum order.

    Two of them: COPY may not write STORED generated columns, but the checksum
    covers them precisely so the target's generation expressions are verified
    rather than trusted.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            select a.attname, a.attgenerated
              from pg_class c
              join pg_namespace n on n.oid = c.relnamespace
              join pg_attribute a on a.attrelid = c.oid
             where n.nspname = %s and c.relname = %s
               and a.attnum > 0 and not a.attisdropped
             order by a.attnum
            """,
            (schema, table),
        )
        rows = cur.fetchall()
    if not rows:
        raise RuntimeError(f"{schema}.{table} does not exist")
    shape = TableShape()
    for row in rows:
        shape.check_columns.append(row["attname"])
        if not row["attgenerated"]:
            shape.copy_columns.append(row["attname"])
    return shape


def public_tables(conn: psycopg.Connection) -> set[str]:
    with conn.cursor() as cur:
        cur.execute(
            """
            select c.relname from pg_class c
              join pg_namespace n on n.oid = c.relnamespace
             where n.nspname = 'public' and c.relkind = 'r'
            """
        )
        return {r["relname"] for r in cur.fetchall()}


def foreign_key_edges(conn: psycopg.Connection) -> set[tuple[str, str]]:
    """(child, parent) pairs, self-references dropped."""
    with conn.cursor() as cur:
        cur.execute(
            """
            select src.relname as child, tgt.relname as parent
              from pg_constraint c
              join pg_class src on src.oid = c.conrelid
              join pg_class tgt on tgt.oid = c.confrelid
              join pg_namespace n on n.oid = src.relnamespace
             where c.contype = 'f' and n.nspname = 'public'
            """
        )
        return {
            (r["child"], r["parent"])
            for r in cur.fetchall()
            if r["child"] != r["parent"]
        }


def identity_sequences(
    conn: psycopg.Connection, tables: list[str], schema: str = "public"
) -> list[tuple[str, str]]:
    """(table, column) for every column backed by a sequence."""
    with conn.cursor() as cur:
        cur.execute(
            """
            select c.relname as tbl, a.attname as col
              from pg_class c
              join pg_namespace n on n.oid = c.relnamespace
              join pg_attribute a on a.attrelid = c.oid
             where n.nspname = %s and c.relkind = 'r'
               and c.relname = any(%s)
               and a.attnum > 0 and not a.attisdropped
               and pg_get_serial_sequence(quote_ident(n.nspname) || '.' ||
                                          quote_ident(c.relname), a.attname) is not null
             order by c.relname
            """,
            (schema, tables),
        )
        return [(r["tbl"], r["col"]) for r in cur.fetchall()]


