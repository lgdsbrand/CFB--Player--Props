def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Copy the development database into the production one.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Default is a dry run: it prints the plan and what the target holds "
            "now, and writes nothing. Use --self-test to prove the copy path "
            "without a production database at all."
        ),
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="actually move the data (truncates each target table first)",
    )
    parser.add_argument(
        "--verify-only",
        action="store_true",
        help="compare row counts and checksums without writing",
    )
    parser.add_argument(
        "--self-test",
        action="store_true",
        help=f"round-trip a small subset into the source's own {SELF_TEST_SCHEMA} schema",
    )
    parser.add_argument(
        "--target-url-env",
        default=TARGET_URL_ENV,
        help=f"environment variable holding the target DSN (default {TARGET_URL_ENV})",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    try:
        settings = get_settings()
    except ConfigError as exc:
        configure_logging("INFO")
        log.error("Configuration error: %s", exc)
        return 2

    configure_logging(settings.log_level)

    src = connect_to(settings.database_url)
    try:
        log.info("Source: %s", _identity(src))

        if args.self_test:
            return self_test(src, settings.database_url)

        target_url = os.environ.get(args.target_url_env)
        if not target_url:
            # A dry run is still worth something with no target — it is the
            # answer to "how much are we about to move, and does it fit under
            # the free tier's 500 MB", which is a question worth answering
            # before the production database exists rather than after.
            if not args.execute and not args.verify_only:
                log.warning(
                    "%s is not set — showing the source side of the plan only.",
                    args.target_url_env,
                )
                render_plan(src, None)
                return 0
            log.error(
                "%s is not set. Put the target's Session pooler DSN (port 5432, "
                "not the 6543 transaction pooler and not the IPv6-only direct "
                "connection) in .env, which is gitignored. Or run --self-test, "
                "which needs no target at all.",
                args.target_url_env,
            )
            return 2

        dst = connect_to(target_url)
        try:
            log.info("Target: %s", _identity(dst))

            distinct, evidence = distinct_databases(src, dst)
            if not distinct:
                log.error("Refusing to run: %s", evidence)
                return 2
            log.debug("Distinct databases: %s.", evidence)

            problems = preflight(src, dst)
            if problems:
                for problem in problems:
                    log.error("pre-flight: %s", problem)
                return 2
            log.info("Pre-flight passed: same schema, ledger complete, distinct databases.")

            if args.verify_only:
                return report_verification(verify(src, dst))

            projected = render_plan(src, dst)
            if not args.execute:
                log.info(
                    "Dry run. Nothing was written. Re-run with --execute to move "
                    "the %.0f MB above.",
                    projected,
                )
                return 0

            return execute(src, dst)
        finally:
            dst.close()
    finally:
        src.close()


if __name__ == "__main__":
    sys.exit(main())
