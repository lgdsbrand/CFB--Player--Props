# Enough of the plan to establish which end is which, without paying for a
# count on all 27 tables twice over a home connection. `player_prop_lines` is
# first because it is the one table whose loss is permanent.
_DIRECTION_WITNESSES = ("player_prop_lines", "plays", "projections", "players")


def check_direction(src: psycopg.Connection, dst: psycopg.Connection) -> list[str]:
    """Refuse to run the migration backwards.

    The failure this exists for: `SUPABASE_DB_URL` and `MIGRATION_TARGET_DB_URL`
    get swapped, the job dutifully truncates the DEVELOPMENT database and copies
    an empty production into it, and 5,752 closing lines that cost ~3,800 Odds
    API credits are gone — with no backup, because the free tier has none.

    `distinct_databases` cannot catch this; both ends really are distinct
    databases. The tell is the direction of the data: the source is the
    populated one.
    """
    problems: list[str] = []

    for table in _DIRECTION_WITNESSES:
        try:
            source_rows = count_rows(src, table)
            target_rows = count_rows(dst, table)
        except psycopg.Error:
            src.rollback()
            dst.rollback()
            continue

        if target_rows > source_rows:
            problems.append(
                f"{table}: the TARGET holds more rows than the SOURCE "
                f"({target_rows:,} vs {source_rows:,}). Either the two URLs are "
                "swapped — SUPABASE_DB_URL must be the development database and "
                f"{TARGET_URL_ENV} the production one — or the target is not as "
                "empty as expected. Nothing has been written."
            )

    if count_rows(src, "player_prop_lines") == 0:
        problems.append(
            "the source has no rows in player_prop_lines. That table holds the "
            "bought closing lines and is never empty on the development "
            "database, so this is almost certainly pointing at the wrong end."
        )

    return problems


def preflight(src: psycopg.Connection, dst: psycopg.Connection) -> list[str]:
    """Every reason not to proceed, gathered in one pass.

    All checks run even after one fails, because a first-time deployment wants
    the whole list rather than one problem per attempt.
    """
    problems: list[str] = check_direction(src, dst)

    ledger_files = sorted(p.name.split("_")[0] for p in MIGRATIONS_DIR.glob("*.sql"))
    with dst.cursor() as cur:
        try:
            cur.execute(
                "select version from supabase_migrations.schema_migrations order by version"
            )
            applied = [str(r["version"]) for r in cur.fetchall()]
        except psycopg.Error:
            dst.rollback()
            applied = []
    missing = [v for v in ledger_files if v not in set(applied)]
    if missing:
        problems.append(
            f"the target's migration ledger is missing {len(missing)} of "
            f"{len(ledger_files)} migrations (first: {missing[0]}). Apply them and "
            "record them — docs/runbook.md#applying-a-migration — before moving data."
        )

    src_tables = public_tables(src)
    dst_tables = public_tables(dst)
    absent = sorted({s.name for s in PLAN} - dst_tables)
    if absent:
        problems.append(f"the target is missing planned table(s): {', '.join(absent)}")

    unplanned = sorted(src_tables - {s.name for s in PLAN} - set(SKIPPED))
    if unplanned:
        problems.append(
            f"the source has table(s) the plan does not mention: {', '.join(unplanned)}. "
            "Add them to PLAN or to SKIPPED — silently leaving a table behind is how "
            "production ends up subtly incomplete."
        )

    for spec in PLAN:
        if spec.name not in dst_tables or spec.name not in src_tables:
            continue
        a = table_shape(src, spec.name)
        b = table_shape(dst, spec.name)
        if a.copy_columns != b.copy_columns:
            problems.append(
                f"{spec.name}: column lists differ between source and target "
                f"(source {a.copy_columns} vs target {b.copy_columns}). The two "
                "schemas are not at the same migration."
            )

    return problems


