def _source_relation(
    spec: TableSpec, columns: list[str], limit: int | None = None
) -> sql.Composed:
    stmt = sql.SQL("select {cols} from {tbl}").format(
        cols=sql.SQL(", ").join(sql.Identifier(c) for c in columns),
        tbl=sql.Identifier("public", spec.name),
    )
    if spec.where:
        stmt = sql.SQL("{base} where {pred}").format(base=stmt, pred=sql.SQL(spec.where))
    if limit is not None:
        # `order by ctid` because an unordered LIMIT picks whichever rows the
        # scan happens to reach first, and the self-test runs this query twice —
        # once to copy and once to checksum. Without the ordering a different
        # plan on the second pass compares two different 5,000-row samples and
        # reports a corruption that never happened. ctid is unique and stable
        # for a table nobody is writing to, and needs no knowledge of the key.
        stmt = sql.SQL("{base} order by ctid limit {n}").format(
            base=stmt, n=sql.Literal(limit)
        )
    return stmt


def checksum(conn: psycopg.Connection, relation: sql.Composed) -> tuple[int, int]:
    """(rows, order-independent hash of every column, generated ones included).

    `sum(hashtext(...))` rather than an ordered digest because it streams: the
    tables here run to hundreds of thousands of rows and aggregating them into
    one sorted array to hash would be the memory-hungriest thing in the job.
    """
    with conn.cursor() as cur:
        cur.execute(
            sql.SQL(
                "select count(*) as n, "
                "coalesce(sum(hashtext(x::text)::bigint), 0) as h from ({rel}) x"
            ).format(rel=relation)
        )
        row = cur.fetchone() or {"n": 0, "h": 0}
    return int(row["n"]), int(row["h"])


def relation_size_mb(conn: psycopg.Connection, table: str) -> float:
    with conn.cursor() as cur:
        cur.execute(
            "select pg_total_relation_size(%s::regclass) / 1024.0 / 1024.0 as mb",
            (f"public.{table}",),
        )
        row = cur.fetchone()
    return float(row["mb"]) if row else 0.0


def database_size_mb(conn: psycopg.Connection) -> float:
    with conn.cursor() as cur:
        cur.execute("select pg_database_size(current_database()) / 1024.0 / 1024.0 as mb")
        row = cur.fetchone()
    return float(row["mb"]) if row else 0.0


def count_rows(conn: psycopg.Connection, table: str, schema: str = "public") -> int:
    with conn.cursor() as cur:
        cur.execute(
            sql.SQL("select count(*) as n from {}").format(sql.Identifier(schema, table))
        )
        row = cur.fetchone()
    return int(row["n"]) if row else 0


def count_selected(conn: psycopg.Connection, spec: TableSpec) -> int:
    """Rows the plan would actually move — the whole table unless it is filtered."""
    stmt = sql.SQL("select count(*) as n from {}").format(sql.Identifier("public", spec.name))
    if spec.where:
        stmt = sql.SQL("{base} where {pred}").format(base=stmt, pred=sql.SQL(spec.where))
    with conn.cursor() as cur:
        cur.execute(stmt)
        row = cur.fetchone()
    return int(row["n"]) if row else 0


