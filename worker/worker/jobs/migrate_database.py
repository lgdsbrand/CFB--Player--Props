"""Copy the development database into the production one — deployment step 5.

    python -m worker.jobs.migrate_database                # the plan, and what the
                                                          # target holds right now
    python -m worker.jobs.migrate_database --self-test    # prove the byte path,
                                                          # no production needed
    python -m worker.jobs.migrate_database --execute      # move the data
    python -m worker.jobs.migrate_database --verify-only  # compare the two ends

Source is `SUPABASE_DB_URL`; target is `MIGRATION_TARGET_DB_URL`. Both are
secrets and neither is ever logged.

THIS IS NOT A RE-INGEST, and the difference is money. `player_prop_lines` holds
5,752 real closing lines bought for ~3,800 Odds API credits, and historical props
are sold per date rather than re-derived — a fresh backfill would come up
silently without them and every profitability number rests on them
(docs/deployment.md §5). So the data moves; it is not regenerated.

WHY BINARY COPY. `pg_dump` and `psql` do not exist on the machine this runs from,
but psycopg 3 streams a `COPY ... TO STDOUT (FORMAT BINARY)` straight into a
`COPY ... FROM STDIN (FORMAT BINARY)` on the other connection without the rows
ever being parsed into Python objects. Binary is safe across two databases *here*
specifically because the only user-defined types in the schema are scalar enums,
which travel as their label text, and the single array column (`backtests.seasons`)
is `int2[]` — a built-in element type whose OID is identical in every database.
An array of an enum or of a composite would embed a per-database OID and would
have to move as text instead. Check that before adding one.

FOUR THINGS THAT SILENTLY CORRUPT A COPY-BASED MIGRATION, all handled here:

  1. **Sequences.** Every `id` is `generated by default as identity`, so COPY
     happily writes explicit ids and leaves all 22 sequences sitting at 1. The
     first production insert then collides on the primary key. `reset_sequences`
     runs after the load and is not optional.
  2. **Generated columns.** `picks.confidence`, `picks.edge`,
     `picks.has_book_line` and `player_game_stats.offensive_tds` are STORED
     generated; COPY refuses to write them. They are excluded from the column
     list and recomputed by the target — and then checksummed, so the target's
     generation expressions are verified rather than assumed.
  3. **Surrogate ids that a fresh schema would renumber.** `sportsbooks` is NOT
     seeded by a migration — its rows were created at runtime by the odds
     adapter and carry gappy ids (1, 24, 25, 26, 27, 34, 39, 81). `conferences`
     IS seeded, but ingest has since grown it past the seed. Both are parents of
     data we are moving, so both are truncated and reloaded with their ids
     intact instead of being left as whatever the target's migrations produced.
  4. **`backtest_predictions` is not all-or-nothing.** See its entry in the plan.

Row triggers are not a problem: the nine `set_updated_at` triggers are BEFORE
UPDATE, and COPY inserts.
"""

