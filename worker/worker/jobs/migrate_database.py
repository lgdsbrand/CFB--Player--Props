def render_plan(src: psycopg.Connection, dst: psycopg.Connection | None) -> float:
    """Print what would move. Returns the projected megabytes."""
    log.info("%-32s %10s %12s  %s", "TABLE", "ROWS", "SIZE", "TARGET NOW")
    total_mb = 0.0
    for spec in PLAN:
        rows = count_selected(src, spec)
        full = count_rows(src, spec.name)
        size = relation_size_mb(src, spec.name)
        moved_mb = size * (rows / full) if full else 0.0
        total_mb += moved_mb
        now = "-"
        if dst is not None:
            try:
                now = f"{count_rows(dst, spec.name):,} rows"
            except psycopg.Error:
                dst.rollback()
                now = "missing"
        suffix = f"  (of {full:,})" if rows != full else ""
        log.info("%-32s %10s %9.1f MB  %s%s", spec.name, f"{rows:,}", moved_mb, now, suffix)

    log.info("%-32s %10s %9.1f MB", "TOTAL", "", total_mb)
    for name, reason in SKIPPED.items():
        log.info("SKIPPED %s — %s", name, reason.split(".")[0].lower())
    log.info(
        "Source database is %.1f MB; roughly %.1f MB lands on the target, "
        "leaving ~%.0f MB under Supabase's 500 MB free-tier cap.",
        database_size_mb(src),
        total_mb,
        500 - total_mb,
    )
    return total_mb


def self_test(src: psycopg.Connection, url: str) -> int:
    """Run the real copy path source-to-source, into a scratch schema.

    The point is to exercise the actual bytes — binary COPY, enums, jsonb,
    int2[], numeric, STORED generated columns and the sequence reset — before
    the production database exists, so deployment night is not the first time
    this code has ever run. Small tables only: the source sits at ~448 MB of a
    500 MB cap and the scratch copies count against it.

    Takes the DSN as well as the open connection because it needs a SECOND one.
    A single connection runs a single statement at a time, and the whole point
    of this job is a `COPY TO STDOUT` feeding a `COPY FROM STDIN` — both live at
    once. Passing the same connection as both ends deadlocks rather than
    failing, which is a memorable way to learn it.
    """
    subset = tuple(
        s
        for s in PLAN
        if s.name
        in {
            "conferences",
            "venues",
            "teams",
            "team_seasons",
            "games",
            "game_weather",
            "markets",
            "market_positions",
            "sportsbooks",
            "app_config",
            "model_runs",
            "backtests",
            "backtest_metrics",
            "calibration_bins",
            # The only small table with STORED generated columns, and the one
            # that proves the target recomputes them to the same values.
            "player_game_stats",
        }
    )

    log.info(
        "Self-test: %d tables into schema %s, up to %s rows each.",
        len(subset),
        SELF_TEST_SCHEMA,
        f"{SELF_TEST_ROWS:,}",
    )
    sink = connect_to(url)
    try:
        with sink.cursor() as cur:
            cur.execute(
                sql.SQL("drop schema if exists {} cascade").format(
                    sql.Identifier(SELF_TEST_SCHEMA)
                )
            )
            cur.execute(sql.SQL("create schema {}").format(sql.Identifier(SELF_TEST_SCHEMA)))
            for spec in subset:
                # INCLUDING ALL carries defaults, identity, constraints and the
                # generated expressions — but not foreign keys, which is what
                # lets the subset be an arbitrary selection rather than a
                # closed one.
                cur.execute(
                    sql.SQL("create table {new} (like {old} including all)").format(
                        new=sql.Identifier(SELF_TEST_SCHEMA, spec.name),
                        old=sql.Identifier("public", spec.name),
                    )
                )
        sink.commit()

        truncate_all(sink, subset, SELF_TEST_SCHEMA)

        for spec in subset:
            rows, written = copy_table(
                src, sink, spec, target_schema=SELF_TEST_SCHEMA, limit=SELF_TEST_ROWS
            )
            log.info("  copied %-30s %8s rows  %6.1f MB", spec.name, f"{rows:,}", written / 1e6)

        moved = reset_sequences(sink, [s.name for s in subset], SELF_TEST_SCHEMA)
        log.info("  reset %d sequence(s)", len(moved))
        for entry in moved:
            log.info("    %s", entry)

        results = verify(src, sink, subset, target_schema=SELF_TEST_SCHEMA, limit=SELF_TEST_ROWS)
        failed = [r for r in results if not r[1]]
        for name, ok, detail in results:
            log.info("  [%s] %-30s %s", "PASS" if ok else "FAIL", name, detail)

        if failed:
            log.error("Self-test FAILED on %d table(s).", len(failed))
            return 1
        log.info("Self-test passed: the copy path is byte-exact on %d tables.", len(subset))
        return 0
    finally:
        sink.rollback()
        with sink.cursor() as cur:
            cur.execute(
                sql.SQL("drop schema if exists {} cascade").format(
                    sql.Identifier(SELF_TEST_SCHEMA)
                )
            )
        sink.commit()
        sink.close()
        log.info("Scratch schema dropped.")


def execute(src: psycopg.Connection, dst: psycopg.Connection) -> int:
    started = time.monotonic()
    total_bytes = 0

    log.info("Emptying %d target tables in one statement.", len(PLAN))
    truncate_all(dst)

    log.info("Loading %d tables in foreign-key order.", len(PLAN))
    for index, spec in enumerate(PLAN, start=1):
        table_started = time.monotonic()
        rows, written = copy_table(src, dst, spec)
        total_bytes += written
        log.info(
            "  [%2d/%2d] %-30s %10s rows  %7.1f MB  %5.1fs",
            index,
            len(PLAN),
            spec.name,
            f"{rows:,}",
            written / 1e6,
            time.monotonic() - table_started,
        )

    log.info("Resetting identity sequences.")
    for entry in reset_sequences(dst, [s.name for s in PLAN]):
        log.info("  %s", entry)

    log.info("Analysing the target so the planner has statistics.")
    dst.commit()
    dst.autocommit = True
    with dst.cursor() as cur:
        for spec in PLAN:
            cur.execute(sql.SQL("analyze {}").format(sql.Identifier("public", spec.name)))
    dst.autocommit = False

    log.info(
        "Moved %.1f MB in %.0fs. Target database is now %.1f MB.",
        total_bytes / 1e6,
        time.monotonic() - started,
        database_size_mb(dst),
    )

    return report_verification(verify(src, dst))


def report_verification(results: list[tuple[str, bool, str]]) -> int:
    failed = [r for r in results if not r[1]]
    for name, ok, detail in results:
        log.info("  [%s] %-30s %s", "PASS" if ok else "FAIL", name, detail)
    if failed:
        log.error(
            "%d of %d tables did not verify: %s",
            len(failed),
            len(results),
            ", ".join(name for name, _, _ in failed),
        )
        return 1
    log.info("All %d tables verified: row counts and checksums agree.", len(results))
    return 0


