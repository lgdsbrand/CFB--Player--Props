def copy_table(
    src: psycopg.Connection,
    dst: psycopg.Connection,
    spec: TableSpec,
    *,
    target_schema: str = "public",
    limit: int | None = None,
) -> tuple[int, int]:
    """Stream the source table into an already-empty target table.

    Emptying is `truncate_all`'s job, not this function's — see the note there
    for why it cannot be done per-table. Returns (rows, bytes), and commits.
    """
    if src is dst:
        # A COPY out and a COPY in are both open at the same moment, and one
        # connection serves one statement at a time. Sharing it does not raise —
        # it deadlocks, and a deadlock during a deployment reads as a slow
        # network. Even the self-test, which copies a database into itself,
        # opens a second connection.
        raise ValueError("copy_table needs two distinct connections, not one twice")

    shape = table_shape(src, spec.name)
    relation = _source_relation(spec, shape.copy_columns, limit)

    copy_out = sql.SQL("copy ({rel}) to stdout (format binary)").format(rel=relation)
    copy_in = sql.SQL("copy {tbl} ({cols}) from stdin (format binary)").format(
        tbl=sql.Identifier(target_schema, spec.name),
        cols=sql.SQL(", ").join(sql.Identifier(c) for c in shape.copy_columns),
    )

    written = 0
    with dst.cursor() as dcur:
        with src.cursor() as scur:
            with scur.copy(copy_out) as source, dcur.copy(copy_in) as sink:
                for block in source:
                    sink.write(block)
                    written += len(block)
    dst.commit()

    rows = count_rows(dst, spec.name, target_schema)
    return rows, written


def truncate_all(
    conn: psycopg.Connection,
    specs: tuple[TableSpec, ...] = PLAN,
    schema: str = "public",
) -> None:
    """Empty every planned table in ONE statement, so a re-run starts clean.

    It has to be one statement. Postgres refuses to `truncate` a table that any
    foreign key references — **whether or not the referencing table holds a
    row** — unless every referencing table is truncated in the same statement or
    CASCADE is used. So a per-table truncate inside the load loop dies on
    `conferences`, the very first table, against a target where the schema
    exists. CASCADE would work and is the wrong tool: it would silently reach
    tables the plan deliberately leaves alone.

    Naming all of them together is safe precisely because the plan is closed
    under "is a parent of" — `test_no_skipped_table_is_a_parent_of_a_planned_one`
    is what keeps that true.

    The consequence worth stating: this job is all-or-nothing. A run that dies
    halfway leaves the target partly loaded, and the fix is to run it again
    rather than to resume it.
    """
    if not specs:
        return
    with conn.cursor() as cur:
        cur.execute(
            sql.SQL("truncate {}").format(
                sql.SQL(", ").join(
                    sql.Identifier(schema, spec.name) for spec in specs
                )
            )
        )
    conn.commit()


def reset_sequences(
    conn: psycopg.Connection, tables: list[str], schema: str = "public"
) -> list[str]:
    """Point every identity sequence past the largest id that was loaded.

    Without this every sequence still reads 1 and the first production insert
    collides on a primary key that COPY filled in explicitly. `is_called=false`
    with `max+1` so the next value is exactly max+1 even for an empty table.
    """
    done: list[str] = []
    for table, column in identity_sequences(conn, tables, schema):
        with conn.cursor() as cur:
            cur.execute(
                sql.SQL(
                    "select setval("
                    "  pg_get_serial_sequence({qualified}, {col}),"
                    "  coalesce((select max({colid}) from {tbl}), 0) + 1,"
                    "  false) as v"
                ).format(
                    qualified=sql.Literal(f"{schema}.{table}"),
                    col=sql.Literal(column),
                    colid=sql.Identifier(column),
                    tbl=sql.Identifier(schema, table),
                )
            )
            row = cur.fetchone()
        done.append(f"{table}.{column} -> {row['v'] if row else '?'}")
    conn.commit()
    return done


def verify(
    src: psycopg.Connection,
    dst: psycopg.Connection,
    specs: tuple[TableSpec, ...] = PLAN,
    *,
    target_schema: str = "public",
    limit: int | None = None,
) -> list[tuple[str, bool, str]]:
    """Compare both ends column-for-column. Returns (table, ok, detail)."""
    results: list[tuple[str, bool, str]] = []
    for spec in specs:
        shape = table_shape(src, spec.name)
        src_rows, src_hash = checksum(src, _source_relation(spec, shape.check_columns, limit))

        dst_relation = sql.SQL("select {cols} from {tbl}").format(
            cols=sql.SQL(", ").join(sql.Identifier(c) for c in shape.check_columns),
            tbl=sql.Identifier(target_schema, spec.name),
        )
        dst_rows, dst_hash = checksum(dst, dst_relation)

        if src_rows != dst_rows:
            results.append(
                (spec.name, False, f"row count {src_rows:,} source vs {dst_rows:,} target")
            )
        elif src_hash != dst_hash:
            results.append(
                (spec.name, False, f"{src_rows:,} rows but the checksums differ")
            )
        else:
            results.append((spec.name, True, f"{src_rows:,} rows, checksums agree"))
    return results


